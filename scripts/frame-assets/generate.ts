/**
 * Builds the frame kit registry (src/image-engine/frame/assets.generated.ts)
 * from assets/frames/manifest.json and the files actually present.
 *
 * Metro bundles only statically required files, so every PNG / layout gets a
 * literal require() here; SVG sources are embedded as strings (parsed once at
 * runtime, see svgFrame.ts). Manifest entries are resolved by file name
 * inside their kind's folder (the kit's frames/ folder is svg/ here).
 *
 *   bun scripts/frame-assets/generate.ts          # write
 *   bun scripts/frame-assets/generate.ts --check  # fail if out of date
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs';
import { basename, join } from 'path';

const ROOT = join(import.meta.dir, '..', '..');
const KIT = join(ROOT, 'assets/frames');
const OUT = join(ROOT, 'src/image-engine/frame/assets.generated.ts');
const REL = '../../../assets/frames';

interface Manifest {
  version: number;
  frames: { id: string; asset: string }[];
  textures: string[];
  decorations: string[];
  layouts: string[];
}

export function generate(): string {
  const manifest = JSON.parse(readFileSync(join(KIT, 'manifest.json'), 'utf8')) as Manifest;
  const need = (path: string) => {
    if (!existsSync(join(KIT, path))) throw new Error(`frame kit: ${path} listed in manifest.json is missing`);
    return path;
  };
  const id = (file: string) => basename(file).replace(/\.[^.]+$/, '');
  const q = (s: string) => JSON.stringify(s);

  const frames = manifest.frames.map((f) => {
    const path = need(`svg/${basename(f.asset)}`);
    return `  ${q(f.id)}: ${q(readFileSync(join(KIT, path), 'utf8').trim())},`;
  });
  const textures = manifest.textures.map((t) => `  ${q(id(t))}: require(${q(`${REL}/${need(`textures/${t}`)}`)}),`);
  const decoPng = manifest.decorations
    .filter((d) => d.endsWith('.png'))
    .map((d) => `  ${q(id(d))}: require(${q(`${REL}/${need(`decorations/${d}`)}`)}),`);
  const decoSvg = manifest.decorations
    .filter((d) => d.endsWith('.svg'))
    .map((d) => `  ${q(id(d))}: ${q(readFileSync(join(KIT, need(`decorations/${d}`)), 'utf8').trim())},`);
  const layouts = manifest.layouts.map((l) => `  ${q(l)}: require(${q(`${REL}/${need(`layouts/${l}.json`)}`)}),`);

  // Files on disk the manifest doesn't mention are reported, not silently bundled.
  const listed = new Set([
    ...manifest.frames.map((f) => `svg/${basename(f.asset)}`),
    ...manifest.textures.map((t) => `textures/${t}`),
    ...manifest.decorations.map((d) => `decorations/${d}`),
    ...manifest.layouts.map((l) => `layouts/${l}.json`),
  ]);
  const unlisted = ['svg', 'textures', 'decorations', 'layouts'].flatMap((dir) =>
    readdirSync(join(KIT, dir)).filter((f) => !f.startsWith('.')).map((f) => `${dir}/${f}`).filter((p) => !listed.has(p)),
  );
  if (unlisted.length) throw new Error(`frame kit: not in manifest.json: ${unlisted.join(', ')}`);

  return `// Generated by scripts/frame-assets/generate.ts from assets/frames — do not edit.
// Run \`npm run frames:generate\` after changing the kit.

import type { LayoutJson } from './registryTypes';

export const FRAME_SVG: Record<string, string> = {
${frames.join('\n')}
};

/** Bundled paper textures (Metro asset modules). */
export const TEXTURE_SOURCES: Record<string, number> = {
${textures.join('\n')}
};

/** Bitmap decorations (tapes). */
export const DECORATION_PNG_SOURCES: Record<string, number> = {
${decoPng.join('\n')}
};

/** Line-art decorations (doodles). */
export const DECORATION_SVG: Record<string, string> = {
${decoSvg.join('\n')}
};

export const LAYOUT_JSON: Record<string, LayoutJson> = {
${layouts.join('\n')}
};
`;
}

if (import.meta.main) {
  const code = generate();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== code) {
      console.error('assets.generated.ts is out of date — run npm run frames:generate');
      process.exit(1);
    }
    console.log('frame registry up to date');
  } else {
    writeFileSync(OUT, code);
    console.log(`wrote ${OUT}`);
  }
}
